#!/usr/bin/env bash
set -euo pipefail
DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$DIR"

EXE=""
if [ -x "./target/release/tally-mcp" ]; then
    EXE="./target/release/tally-mcp"
elif [ -x "./target/debug/tally-mcp" ]; then
    EXE="./target/debug/tally-mcp"
else
    cargo build --quiet
    EXE="./target/debug/tally-mcp"
fi

export MD_TOOLS=$("$EXE" tools --markdown)

node -e '
const fs = require("fs");
const toolsMd = process.env.MD_TOOLS;
let content = fs.readFileSync("readme.md", "utf8");
const startMarker = "<!-- tools:start -->";
const endMarker = "<!-- tools:end -->";
const startIndex = content.indexOf(startMarker);
const endIndex = content.indexOf(endMarker);
if (startIndex === -1 || endIndex === -1) {
    console.error("Tools markers not found in readme.md");
    process.exit(1);
}
const before = content.slice(0, startIndex + startMarker.length);
const after = content.slice(endIndex);
const replacement = "\n<!-- generated by scripts/gen-readme.sh from `tally-mcp tools --markdown`; do not edit -->\n" + toolsMd + "\n";
fs.writeFileSync("readme.md", before + replacement + after, "utf8");
'
